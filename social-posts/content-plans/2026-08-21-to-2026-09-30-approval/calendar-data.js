function altCamTopicTags(item) {
  const text = `${item.title} ${item.description}`.toLowerCase();
  if (/домофон|викличн|замок|хвіртк/.test(text)) return ['#домофон', '#відеодомофон', '#контрольдоступу'];
  if (/ajax|датчик|сирен/.test(text)) return ['#ajaxsystems', '#охороннасигналізація', '#розумнийдім'];
  if (/резерв|ups|lifepo4|автоном/.test(text)) return ['#резервнеживлення', '#безперебійнеживлення', '#lifepo4'];
  if (/кабел|utp|poe|конектор|кронштейн|коробк/.test(text)) return ['#кабель', '#poe', '#монтажкамер'];
  if (/скуд|доступ|картк|ключ/.test(text)) return ['#скуд', '#контрольдоступу', '#безпекаофісу'];
  if (/архів|nvr|реєстратор|hdd|шаф/.test(text)) return ['#відеореєстратор', '#nvr', '#відеоархів'];
  return ['#відеоспостереження', '#камеривідеоспостереження', '#монтажкамер'];
}

